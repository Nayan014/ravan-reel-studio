"""Generate the public demo from code, colour cards and quiet test tones only."""
import argparse
import json
from pathlib import Path
import shutil
import subprocess
import tempfile
from PIL import Image,ImageDraw,ImageFont

ROOT=Path(__file__).resolve().parents[1]

def generate(target):
    target=Path(target)
    if target.exists():raise ValueError('Destination exists. Choose a new path; no files were overwritten.')
    font_file=ROOT/'skills/effects/fonts/Inter.ttf'
    font=ImageFont.truetype(str(font_file),56);small=ImageFont.truetype(str(font_file),27)
    labels=[('RAVAN REEL','STUDIO'),('REVIEW YOUR','FRAMES'),('YOUR REEL,','YOUR CHOICE')]
    colours=['#345554','#95634b','#3c4657']
    with tempfile.TemporaryDirectory(prefix='ravan-synthetic-') as temporary:
        work=Path(temporary);lines=[]
        for i,(words,colour) in enumerate(zip(labels,colours)):
            image=Image.new('RGB',(720,1280),colour);draw=ImageDraw.Draw(image)
            def center(text,y,face):
                bounds=draw.textbbox((0,0),text,font=face);width=bounds[2]-bounds[0]
                draw.text(((720-width)/2,y),text,font=face,fill='white')
            center('SYNTHETIC DEMO',125,small)
            center(words[0],500,font);center(words[1],585,font)
            center('No personal footage or speech',1085,small)
            file=work/f'{i}.png';image.save(file)
            lines += [f"file '{file.as_posix()}'",'duration 2']
        lines.append(f"file '{file.as_posix()}'");(work/'timeline.txt').write_text('\n'.join(lines)+'\n')
        subprocess.run(['ffmpeg','-y','-v','error','-f','concat','-safe','0','-i',str(work/'timeline.txt'),
                        '-f','lavfi','-i',r'aevalsrc=sin(2*PI*440*t)*0.025*lt(mod(t\,2)\,0.12):s=48000:d=6',
                        '-t','6','-vf','fps=30','-frames:v','180','-c:v','libx264','-preset','medium','-crf','24',
                        '-pix_fmt','yuv420p','-c:a','aac','-b:a','64k','-movflags','+faststart',str(work/'demo.mp4')],check=True)
        (target/'export').mkdir(parents=True)
        shutil.copy2(work/'demo.mp4',target/'export/demo.mp4');shutil.copy2(work/'0.png',target/'export/cover.png')
    (target/'export/caption.txt').write_text('Ravan Reel Studio synthetic demo.\n\nGenerated colour cards and quiet test tones. No personal footage, real voice, AI-generated person or recorded speech.\n')
    (target/'export.json').write_text(json.dumps({'synthetic':True,'file':'export/demo.mp4','cover':{'png':'export/cover.png'},
        'duration':6,'width':720,'height':1280,'fps':30,'caption_ready':True,
        'generator':'examples/generate_demo.py','notice':'Pre-rendered demonstration only; not an approved workflow export or a Vibha effect showcase.'},indent=2)+'\n')
    (target/'README.md').write_text('''# Synthetic dashboard demo

This six-second portrait video contains generated colour cards and quiet test tones. It contains **no personal recordings, faces or spoken voice**. The on-screen text is graphic labelling, not transcribed captions. It demonstrates dashboard playback, covers, posting copy and downloads; it is not a showcase of Vibha effects or an approved workflow render.

From the repository root, run `npm start` for automatic setup and browser opening. For a demo-only install without production dependencies, run `npm run demo`, then `npm run dashboard`. The installer copies this package into `outputs/reels/synthetic-demo` and refuses to overwrite an existing project. Installed demo files remain ignored by Git, just like every other generated output.

The only public video exception is `examples/demo/export/demo.mp4`. Keep personal files in `inputs/`; do not replace this fixture with recorded footage. The public packager also rejects other video files, even outside the usual media folders.

To reproduce in a different destination after installing effects dependencies and ffmpeg:

```bash
skills/effects/.venv/bin/python examples/generate_demo.py --output outputs/rebuilt-demo
```

Generated by Techno Ravan for Ravan Reel Studio, under the project MIT licence. Typography uses the bundled Inter font, whose notice remains in `skills/effects/fonts/OFL-Inter.txt`. No external media or voice service is used.
''')
    return {'folder':str(target),'synthetic':True,'duration':6}

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--output',type=Path,default=ROOT/'examples/demo');args=p.parse_args()
    print(json.dumps(generate(args.output)))
